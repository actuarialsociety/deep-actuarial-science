"""Paper-to-code checklist: is each model implemented as its benchmark paper says?

`docs/paper_checklist.yml` lists, per model, the paper's components (architecture, equations,
hyperparameters, data handling) with where the paper states them and whether our code matches,
deviates (with the reason) or the source is silent. This module loads it, fills in what our
code does from the live parameters (`conf/base`), and reports any item that has drifted:

- an item with `param` must equal that parameter's current value;
- an item with `code` must name a symbol that still exists.

`pytest` fails on a problem, so the checklist cannot go stale; `scripts/build_docs.py` renders
it into the report and `docs/paper_checklist.md`.
"""

from __future__ import annotations

import importlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs" / "paper_checklist.yml"
STATUSES = {"match": "✓ as in the paper", "deviation": "≠ deviation", "open": "? not stated"}


def parameters() -> dict:
    """Every `conf/base/parameters*.yml`, merged (the reference setup)."""
    out: dict = {}
    for f in sorted((ROOT / "conf" / "base").glob("parameters*.yml")):
        out.update(yaml.safe_load(f.read_text()) or {})
    return out


def _lookup(params: dict, path: str):
    """Value at a dotted path, e.g. `frequency.models.fnn.hidden`."""
    for key in path.split("."):
        params = params[key]
    return params


def _symbol_exists(ref: str) -> bool:
    """`models/frequency.py::EmbeddingFNN` -> does that module have that attribute?"""
    file, _, name = ref.partition("::")
    module = "deep_actuarial_science." + file.removesuffix(".py").replace("/", ".")
    return hasattr(importlib.import_module(module), name)


def load() -> dict:
    """The checklist, each item completed with `ours` (from the parameter when it has one)."""
    params, models = parameters(), yaml.safe_load(SOURCE.read_text())
    for model in models.values():
        for item in model["items"]:
            if "param" in item:
                item["ours"] = f"`{item['param'].split('.')[-1]}: {_lookup(params, item['param'])}`"
    return models


def problems() -> list[str]:
    """Items that no longer agree with the code or the parameters (empty = all good)."""
    params, out = parameters(), []
    for key, model in yaml.safe_load(SOURCE.read_text()).items():
        for item in model["items"]:
            where = f"{key}: {item['what']}"
            if item.get("status") not in STATUSES:
                out.append(f"{where}: status must be one of {sorted(STATUSES)}")
            if item["status"] == "deviation" and not item.get("note"):
                out.append(f"{where}: a deviation needs a note giving its reason")
            if "param" in item and _lookup(params, item["param"]) != item["value"]:
                out.append(f"{where}: {item['param']} is no longer {item['value']}")
            if "code" in item and not _symbol_exists(item["code"]):
                out.append(f"{where}: {item['code']} not found")
            if "param" not in item and "code" not in item:
                out.append(f"{where}: needs a `param` or a `code` pointer")
    return out


def summary(models: dict | None = None) -> dict[str, int]:
    """Number of items per status over the whole checklist."""
    counts = dict.fromkeys(STATUSES, 0)
    for model in (models or load()).values():
        for item in model["items"]:
            counts[item["status"]] += 1
    return counts


def markdown(models: dict | None = None) -> str:
    """The checklist as a Markdown page: one table per model."""
    models = models or load()
    n = summary(models)
    lines = [
        "# Implemented as in the paper?",
        "",
        "Generated by `scripts/build_docs.py` from `docs/paper_checklist.yml` (never edit by "
        "hand). Each row sets one component of a benchmark paper against this repository's "
        "code; `pytest` fails when a parameter or symbol named here changes.",
        "",
        f"**{n['match']}** as in the paper · **{n['deviation']}** documented deviations · "
        f"**{n['open']}** where the source is silent or not yet read.",
    ]
    for key, m in models.items():
        link = f"https://doi.org/{m['doi']}" if m.get("doi") else m.get("url", "")
        src = f"[{m['paper']}]({link})" if link else m["paper"]
        src += f" · [code]({m['code']})" if m.get("code") else ""
        lines += ["", f"## {m['title']} (`{key}`)", "", src, ""]
        lines += ["| Component | Paper | Where | Ours | Status |", "|" + " --- |" * 5]
        for i in m["items"]:
            status = STATUSES[i["status"]] + (f": {i['note']}" if i.get("note") else "")
            code = f" (`{i['code']}`)" if i.get("code") else ""
            cells = [i["what"], str(i["paper"]), i["where"], i["ours"] + code, status]
            lines.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    return "\n".join(lines) + "\n"
